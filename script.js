const tooltip = byId("tooltip");

function drawMarker(parent, shape, cx, cy, size, color, ring) {
  const common = { fill: color };
  if (ring) Object.assign(common, { stroke: SURFACE, "stroke-width": 2 });
  const half = size / 2;
  if (shape === "square") return svgEl("rect", { x: cx - half, y: cy - half, width: size, height: size, rx: 1.5, ...common }, parent);
  if (shape === "triangle") {
    const r = half * 1.3;
    return svgEl("path", { d: `M${cx} ${cy - r}L${cx + r} ${cy + r * .8}L${cx - r} ${cy + r * .8}Z`, ...common }, parent);
  }
  if (shape === "diamond") {
    const r = half * 1.25;
    return svgEl("path", { d: `M${cx} ${cy - r}L${cx + r} ${cy}L${cx} ${cy + r}L${cx - r} ${cy}Z`, ...common }, parent);
  }
  return svgEl("circle", { cx, cy, r: half, ...common }, parent);
}

function markerIcon(parent, series) {
  const icon = svgEl("svg", { viewBox: "0 0 14 14", "aria-hidden": "true", focusable: "false" }, parent);
  drawMarker(icon, series.shape, 7, 7, 9, series.color, false);
  return icon;
}

function showTooltip(event, title, rows) {
  tooltip.textContent = "";
  addText(tooltip, "div", title, "tooltip-title");
  rows.forEach(row => {
    const line = addText(tooltip, "div", "", "tooltip-row");
    if (row.series) markerIcon(line, row.series);
    else if (row.color) { const swatch = addText(line, "span", "", "swatch"); swatch.style.background = row.color; }
    addText(line, "strong", row.value);
    if (row.name) addText(line, "span", row.name, "name");
  });
  tooltip.hidden = false;
  const box = tooltip.getBoundingClientRect();
  let x, y;
  if (event.type.startsWith("pointer") || event.type.startsWith("mouse")) {
    x = event.clientX + 14; y = event.clientY + 14;
  } else {
    const target = event.currentTarget.getBoundingClientRect();
    x = target.left + target.width / 2 - box.width / 2; y = target.top - box.height - 8;
  }
  x = Math.max(8, Math.min(x, window.innerWidth - box.width - 8));
  if (y + box.height > window.innerHeight - 8) y = Math.max(8, y - box.height - 28);
  tooltip.style.left = x + "px";
  tooltip.style.top = Math.max(8, y) + "px";
}

function hideTooltip() { tooltip.hidden = true; }

function addHover(target, group, title, rows) {
  const on = event => { if (group) group.classList.add("is-active"); showTooltip(event, title, rows); };
  const off = () => { if (group) group.classList.remove("is-active"); hideTooltip(); };
  target.addEventListener("pointerenter", on);
  target.addEventListener("pointermove", on);
  target.addEventListener("pointerleave", off);
  target.addEventListener("focus", on);
  target.addEventListener("blur", off);
}

// Charts are drawn at the real width of their container, so text stays 12px on phones.
function responsive(host, draw) {
  let lastWidth = 0;
  const run = () => {
    const width = Math.round(host.clientWidth);
    if (!width || width === lastWidth) return;
    lastWidth = width;
    host.textContent = "";
    draw(Math.max(280, width));
  };
  run();
  window.addEventListener("resize", run);
}

