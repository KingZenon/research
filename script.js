function drawFatalShareChart(host, years, W) {
  const H = 260, m = { l: 40, r: 16, t: 24, b: 30 };
  const plotW = W - m.l - m.r, plotH = H - m.t - m.b;
  const yMax = Math.ceil(Math.max(...years.map(d => d.fatalShare)) * 100 / 4) * 4 / 100;
  const band = plotW / years.length;
  const x = i => m.l + band * (i + .5);
  const y = v => m.t + plotH * (1 - v / yMax);
  const svg = svgEl("svg", { viewBox: `0 0 ${W} ${H}`, role: "group",
    "aria-label": `Line chart of the fatal share of incidents by year, from ${percent(years[0].fatalShare)} in ${years[0].year} to ${percent(years[years.length - 1].fatalShare)} in ${years[years.length - 1].year}` }, host);
  for (let tick = 0; tick <= yMax + 1e-9; tick += .04) {
    svgEl("line", { class: tick === 0 ? "axis" : "grid", x1: m.l, x2: W - m.r, y1: y(tick), y2: y(tick) }, svg);
    svgEl("text", { x: m.l - 8, y: y(tick) + 4, "text-anchor": "end" }, svg).textContent = Math.round(tick * 100) + "%";
  }
  const points = years.map((d, i) => `${x(i)} ${y(d.fatalShare)}`);
  svgEl("path", { d: `M${x(0)} ${y(0)}L${points.join("L")}L${x(years.length - 1)} ${y(0)}Z`, fill: SERIES.default.color, opacity: .1 }, svg);
  svgEl("path", { d: "M" + points.join("L"), fill: "none", stroke: SERIES.default.color, "stroke-width": 2, "stroke-linejoin": "round", "stroke-linecap": "round" }, svg);
  years.forEach((d, i) => {
    const group = svgEl("g", {}, svg);
    svgEl("line", { class: "crosshair", x1: x(i), x2: x(i), y1: m.t, y2: y(0) }, group);
    svgEl("circle", { cx: x(i), cy: y(d.fatalShare), r: 4, fill: SERIES.default.color, stroke: SURFACE, "stroke-width": 2 }, group);
    if (band >= 34 || (years.length - 1 - i) % 2 === 0) svgEl("text", { x: x(i), y: H - 9, "text-anchor": "middle" }, group).textContent = d.year;
    if (i === 0 || i === years.length - 1) {
      svgEl("text", { class: "value-label", x: x(i), y: y(d.fatalShare) - 11, "text-anchor": "middle" }, group).textContent = percent(d.fatalShare);
    }
    const hit = svgEl("rect", { class: "hit", x: m.l + band * i, y: m.t - 12, width: band, height: plotH + 12, tabindex: 0, role: "img",
      "aria-label": `${d.year}: ${percent(d.fatalShare)} fatal, ${count(d.fatal)} of ${count(d.total)} incidents` }, group);
    addHover(hit, group, String(d.year), [
      { series: SERIES.default, value: percent(d.fatalShare), name: "fatal share" },
      { value: count(d.fatal), name: `fatal of ${count(d.total)} incidents` }
    ]);
  });
}

