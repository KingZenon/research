// Like responsive(), but returns a function that forces a redraw (used when the model choice changes).
function redrawable(host, draw) {
  let lastWidth = 0;
  const run = force => {
    const width = Math.round(host.clientWidth);
    if (!width || (!force && width === lastWidth)) return;
    lastWidth = width;
    host.textContent = "";
    draw(Math.max(280, width));
  };
  run(false);
  window.addEventListener("resize", () => run(false));
  return () => run(true);
}

const CLASS_SHORT = ["Fatal", "Injury", "Property only"];
const rowSum = row => row.reduce((a, b) => a + b, 0);

function fatalStats(matrix) {
  const predicted = matrix[0][0] + matrix[1][0] + matrix[2][0];
  return { recall: matrix[0][0] / rowSum(matrix[0]), precision: predicted ? matrix[0][0] / predicted : 0 };
}

function buildMatrixTable(parent, matrix, caption) {
  const table = addText(parent, "table", "", "cm");
  addText(table, "caption", caption, "sr-only");
  const header = addText(addText(table, "thead", ""), "tr", "");
  addText(header, "th", "Actual \\ predicted").scope = "col";
  CLASS_SHORT.forEach(name => { addText(header, "th", name).scope = "col"; });
  const body = addText(table, "tbody", "");
  matrix.forEach((counts, actual) => {
    const row = addText(body, "tr", "");
    addText(row, "th", CLASS_SHORT[actual]).scope = "row";
    const total = rowSum(counts);
    counts.forEach((value, predicted) => {
      const share = total ? value / total : 0;
      const cell = addText(row, "td", "", "cm-cell" + (actual === predicted ? " diag" : ""));
      cell.style.background = `rgba(42, 120, 214, ${(.06 + .86 * share).toFixed(3)})`;
      cell.style.color = share > .5 ? "#fff" : "var(--ink)";
      addText(cell, "span", percent(share), "cm-pct");
      addText(cell, "span", count(value), "cm-n");
    });
  });
  return table;
}

function drawConfusion(host, model) {
  host.textContent = "";
  FIGURE_VARIANTS.forEach(variant => {
    const matrix = model.confusion[variant];
    const stats = fatalStats(matrix);
    const panel = addText(host, "div", "", "cm-panel");
    const head = addText(panel, "div", "", "cm-head");
    markerIcon(head, SERIES[variant]);
    addText(head, "strong", SERIES[variant].label);
    addText(panel, "p", `Fatal recall ${score(stats.recall)} · precision ${score(stats.precision)}`, "cm-stats");
    buildMatrixTable(panel, matrix, `${model.label}, ${SERIES[variant].label.toLowerCase()}: share of each actual class (rows) given each predicted class (columns), with incident counts.`);
  });
}

