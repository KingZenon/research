/* ---------- results ---------- */
const TABLE_METRICS = ["fatal_recall", "fatal_precision", "fatal_f1", "fatal_pr_auc", "macro_f1", "balanced_acc"];
const meanOf = (entry, metric) => entry.metrics[metric][0];
const pick = (model, variant) => measured.models.find(entry => entry.model === model && entry.variant === variant);
const bestBy = metric => measured.models.reduce((best, entry) => (meanOf(entry, metric) > meanOf(best, metric) ? entry : best));

function renderResultStats() {
  const host = byId("result-stats");
  const tiles = [];
  const plain = pick("xgboost", "default"), weighted = pick("xgboost", "class_weight");
  if (plain && weighted) tiles.push({ value: `${meanOf(plain, "fatal_recall").toFixed(2)} → ${meanOf(weighted, "fatal_recall").toFixed(2)}`,
    label: "Fatal recall, XGBoost", sub: "default → with class weights" });
  const f1 = bestBy("fatal_f1");
  tiles.push({ value: score(meanOf(f1, "fatal_f1")), label: "Best fatal F1", sub: `${f1.label} · ${f1.variantLabel.toLowerCase()}` });
  const macro = bestBy("macro_f1"), baseline = pick("majority_class", "default");
  tiles.push({ value: score(meanOf(macro, "macro_f1")), label: "Best macro-F1",
    sub: `${macro.label} · ${macro.variantLabel.toLowerCase()}` + (baseline ? ` (majority baseline ${score(meanOf(baseline, "macro_f1"))})` : "") });
  tiles.forEach(item => {
    const tile = addText(host, "div", "", "stat");
    addText(tile, "span", item.value, "stat-value");
    addText(tile, "span", item.label, "stat-label");
    addText(tile, "span", item.sub, "stat-sub");
  });
}

function renderVariantChart(host, metric, title, xMax) {
  const panel = addText(host, "div", "");
  addText(panel, "p", title, "chart-title");
  const chart = addText(panel, "div", "", "chart");
  responsive(chart, W => drawVariantChart(chart, metric, title, xMax, W));
}

function drawVariantChart(chart, metric, title, xMax, W) {
  const models = [...new Set(measured.models.filter(entry => entry.model !== "majority_class").map(entry => entry.model))];
  const rowH = 46, m = { l: 122, r: 16, t: 8, b: 30 };
  const plotW = W - m.l - m.r, H = m.t + rowH * models.length + m.b;
  const x = v => m.l + plotW * (v / xMax);
  const svg = svgEl("svg", { viewBox: `0 0 ${W} ${H}`, role: "group", "aria-label": `${title} by model and variant` }, chart);
  for (let tick = 0; tick <= xMax + 1e-9; tick += .2) {
    svgEl("line", { class: tick === 0 ? "axis" : "grid", x1: x(tick), x2: x(tick), y1: m.t, y2: H - m.b }, svg);
    svgEl("text", { x: x(tick), y: H - 9, "text-anchor": "middle" }, svg).textContent = tick.toFixed(1);
  }
  const lanes = { default: -12, class_weight: 0, prior_adjusted: 12 };
  models.forEach((model, index) => {
    const entries = measured.models.filter(entry => entry.model === model);
    const cy = m.t + rowH * (index + .5);
    const group = svgEl("g", {}, svg);
    svgEl("rect", { class: "hover-band", x: 0, y: cy - rowH / 2 + 2, width: W, height: rowH - 4, rx: 6 }, group);
    svgEl("text", { class: "row-label", x: m.l - 12, y: cy + 4, "text-anchor": "end" }, group).textContent = entries[0].label;
    entries.forEach(entry => {
      const series = SERIES[entry.variant];
      const [mean, sd] = entry.metrics[metric];
      const y = cy + lanes[entry.variant];
      svgEl("line", { x1: x(Math.max(0, mean - sd)), x2: x(Math.min(xMax, mean + sd)), y1: y, y2: y, stroke: series.color, "stroke-width": 2, "stroke-linecap": "round", opacity: .45 }, group);
      drawMarker(group, series.shape, x(mean), y, 9, series.color, true);
    });
    const describe = entry => `${entry.variantLabel} ${score(entry.metrics[metric][0])} plus or minus ${score(entry.metrics[metric][1])}`;
    const hit = svgEl("rect", { class: "hit", x: 0, y: cy - rowH / 2, width: W, height: rowH, tabindex: 0, role: "img",
      "aria-label": `${entries[0].label}, ${title.toLowerCase()}: ${entries.map(describe).join("; ")}` }, group);
    addHover(hit, group, `${entries[0].label} · ${title.toLowerCase()}`, entries.map(entry => ({
      series: SERIES[entry.variant], value: `${score(entry.metrics[metric][0])} ± ${score(entry.metrics[metric][1])}`, name: entry.variantLabel
    })));
  });
}

function renderResults() {
  const results = project.results;
  byId("results-status").textContent = results.status;
  byId("results-summary").textContent = results.summary;
  addList(byId("results-takeaways"), results.takeaways || []);
  addList(byId("results-limits"), results.limits || []);
  const body = byId("model-rows");

  if (!measured || measured.models.length === 0) {
    const row = document.createElement("tr");
    addText(row, "td", "No measured model results have been supplied.").colSpan = 8;
    body.appendChild(row);
    byId("variant-chart-card").hidden = true;
  } else {
    renderResultStats();
    Object.values(SERIES).forEach(series => { const item = addText(byId("variant-legend"), "li", ""); markerIcon(item, series); addText(item, "span", series.label); });
    const charted = measured.models.filter(entry => entry.model !== "majority_class");
    const top = Math.max(...charted.flatMap(entry => ["fatal_recall", "fatal_precision"].map(k => entry.metrics[k][0] + entry.metrics[k][1])));
    const xMax = Math.min(1, Math.ceil(top / .2) * .2);
    renderVariantChart(byId("result-figures"), "fatal_recall", "Fatal recall", xMax);
    renderVariantChart(byId("result-figures"), "fatal_precision", "Fatal precision", xMax);

    const VARIANT_NOTES = {
      default: "Plain model, no imbalance handling.",
      class_weight: "Rare classes are weighted more heavily during training.",
      prior_adjusted: "Plain model, but each class probability is divided by its training share before the label is chosen."
    };
    const variantKeys = Object.keys(VARIANT_NOTES).filter(key => measured.models.some(entry => entry.variant === key));
    const baselineEntry = pick("majority_class", "default");
    const tabs = byId("variant-tabs");
    const drawTable = variant => {
      body.textContent = "";
      const rows = measured.models.filter(entry => entry.variant === variant && entry.model !== "majority_class");
      const best = Object.fromEntries(TABLE_METRICS.map(metric => [metric, Math.max(...rows.map(entry => meanOf(entry, metric)))]));
      const addRow = (entry, isBaseline) => {
        const row = document.createElement("tr");
        if (isBaseline) row.className = "baseline-row";
        addText(row, "td", entry.label, "model-name");
        TABLE_METRICS.forEach(metric => {
          const [mean, sd] = entry.metrics[metric];
          const cell = addText(row, "td", "", !isBaseline && mean === best[metric] ? "best" : "");
          addText(cell, "span", score(mean), "val");
          addText(cell, "span", "± " + score(sd), "sd");
        });
        body.appendChild(row);
      };
      rows.forEach(entry => addRow(entry, false));
      if (baselineEntry) addRow(baselineEntry, true);
      byId("variant-desc").textContent = VARIANT_NOTES[variant];
      tabs.querySelectorAll("button").forEach(button => button.setAttribute("aria-pressed", String(button.dataset.variant === variant)));
    };
    variantKeys.forEach(key => {
      const button = addText(tabs, "button", SERIES[key].label);
      button.type = "button";
      button.dataset.variant = key;
      button.addEventListener("click", () => drawTable(key));
    });
    drawTable(variantKeys[0]);
    const folds = measured.folds;
    byId("model-table-note").textContent = `Mean over ${measured.nFolds} temporal folds (validation years ${folds[0].validation}–${folds[folds.length - 1].validation}). The 2026 test year has not been used.`;
  }

  const draft = results.draft || {};
  [["working", "What is working", "✓", draft.working], ["not-working", "What is not working yet", "!", draft.notWorking], ["fix", "How we plan to solve it", "→", draft.fixes]].forEach(([kind, title, icon, items]) => {
    if (!items || items.length === 0) return;
    const card = addText(byId("draft-status"), "article", "", "card draft-card " + kind);
    const heading = addText(card, "h3", "");
    addText(heading, "span", icon, "draft-icon").setAttribute("aria-hidden", "true");
    addText(heading, "span", title);
    const list = addText(card, "ul", "");
    items.forEach(item => addText(list, "li", item));
  });
}

