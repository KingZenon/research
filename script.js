/* ---------- navigation ---------- */
function setupNavigation() {
  const button = document.querySelector(".menu-toggle");
  const links = byId("nav-links");

  function closeMenu() {
    links.classList.remove("open");
    button.setAttribute("aria-expanded", "false");
    button.setAttribute("aria-label", "Open navigation");
  }

  button.addEventListener("click", () => {
    const open = links.classList.toggle("open");
    button.setAttribute("aria-expanded", String(open));
    button.setAttribute("aria-label", open ? "Close navigation" : "Open navigation");
  });
  links.querySelectorAll("a").forEach(link => link.addEventListener("click", closeMenu));
  document.addEventListener("keydown", event => {
    if (event.key === "Escape") { closeMenu(); hideTooltip(); }
  });

  // highlight the section currently in view
  if ("IntersectionObserver" in window) {
    const byHash = Object.fromEntries([...links.querySelectorAll("a")].map(link => [link.getAttribute("href").slice(1), link]));
    const observer = new IntersectionObserver(entries => {
      entries.forEach(entry => {
        const link = byHash[entry.target.id];
        if (!link || !entry.isIntersecting) return;
        Object.values(byHash).forEach(other => other.removeAttribute("aria-current"));
        link.setAttribute("aria-current", "true");
      });
    }, { rootMargin: "-40% 0px -55% 0px" });
    Object.keys(byHash).forEach(id => { const section = byId(id); if (section) observer.observe(section); });
  }
  window.addEventListener("scroll", hideTooltip, { passive: true });
}

