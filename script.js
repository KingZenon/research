function renderSeverityBar() {
  const bar = byId("severity-bar");
  const legend = byId("severity-legend");
  if (!measured) { addText(bar.parentElement, "p", "Class counts will appear when the measured data file is added.", "empty-note"); bar.remove(); return; }
  const totals = measured.classTotals;
  bar.setAttribute("role", "group");
  bar.setAttribute("aria-label", "Share of incidents by severity class: " +
    SEVERITY.map(part => `${part.label} ${percent(totals[part.key] / totals.total)}`).join(", "));
  SEVERITY.forEach(part => {
    const share = totals[part.key] / totals.total;
    const segment = addText(bar, "div", "", "seg" + (part.onLight ? " on-light" : ""));
    segment.style.flex = `${totals[part.key]} 1 0`;
    segment.style.background = part.color;
    segment.tabIndex = 0;
    segment.setAttribute("aria-label", `${part.label}: ${count(totals[part.key])} incidents, ${percent(share)}`);
    const label = addText(segment, "span", percent(share));
    label.style.paddingLeft = "9px";
    addHover(segment, null, part.label, [{ color: part.color, value: percent(share), name: `${count(totals[part.key])} incidents` }]);
    const item = addText(legend, "li", "");
    const swatch = addText(item, "span", "", "swatch");
    swatch.style.background = part.color;
    addText(item, "span", part.label);
  });
  // a share label is shown only when it fits inside its block; the value stays in the legend row's tooltip and the text above
  const fit = () => bar.querySelectorAll(".seg").forEach(segment => {
    const label = segment.firstElementChild;
    label.hidden = false;
    label.hidden = label.offsetWidth + 6 > segment.clientWidth;
  });
  fit();
  window.addEventListener("resize", fit);
}

