"""Write the measured numbers used by the project website into website/results-data.js.

Usage:  python -I -X utf8 export_site_results.py <combined_csv> <results_dir> <site_dir>

Everything on the website's charts and results table comes from this file, and this file
comes only from the experiment outputs (cv_thai_all_*.csv, written by aggregate_final.py, or the Milestone 3
cv_temporal_thai_*.csv if those do not exist yet) and the harmonised table.
No score is typed by hand.
"""
import json
import sys
from pathlib import Path

import pandas as pd

MODEL_LABELS = {"majority_class": "Majority class (baseline)", "logistic_regression": "Logistic regression",
                "decision_tree": "Decision tree", "random_forest": "Random forest",
                "xgboost": "XGBoost", "lightgbm": "LightGBM",
                "xgboost_tuned": "XGBoost (tuned)", "lightgbm_tuned": "LightGBM (tuned)"}
VARIANT_LABELS = {"default": "Default", "class_weight": "Class weights", "prior_adjusted": "Prior-adjusted", "smote": "SMOTE-NC"}
METRICS = ["fatal_recall", "fatal_precision", "fatal_f1", "fatal_pr_auc", "fatal_auc",
           "macro_f1", "balanced_acc", "mcc", "accuracy"]


def main(combined_csv, results_dir, site_dir):
    results_dir, site_dir = Path(results_dir), Path(site_dir)
    final = (results_dir / "cv_thai_all_summary.csv").exists()
    summary = pd.read_csv(results_dir / ("cv_thai_all_summary.csv" if final else "cv_temporal_thai_summary.csv"))
    folds = pd.read_csv(results_dir / ("cv_thai_all_folds.csv" if final else "cv_temporal_thai_folds.csv"))

    models = []
    for m in MODEL_LABELS:                      # fixed display order
        for v in VARIANT_LABELS:
            row = summary[(summary.model == m) & (summary.variant == v)]
            if row.empty:
                continue
            r = row.iloc[0]
            models.append({
                "model": m, "label": MODEL_LABELS[m], "variant": v, "variantLabel": VARIANT_LABELS[v],
                "metrics": {k: [round(float(r[f"{k}_mean"]), 6), round(float(r[f"{k}_std"]), 6)] for k in METRICS},
            })

    one = folds[(folds.model == "majority_class") & (folds.variant == "default")].sort_values("val_year")
    first_year = 2019
    fold_rows = [{"train": f"{first_year}–{int(r.val_year) - 1}", "validation": int(r.val_year),
                  "nTrain": int(r.n_train), "nValidation": int(r.n_val),
                  "fatalShareValidation": round(float(r.fatal_share_val), 6)} for r in one.itertuples()]

    d = pd.read_csv(combined_csv, encoding="utf-8-sig", low_memory=False, usecols=["acc_year", "severity"]).dropna()
    counts = pd.crosstab(d["acc_year"].astype(int), d["severity"])
    years = [{"year": int(y), "fatal": int(r["fatal"]), "injury": int(r["injury"]),
              "propertyOnly": int(r["property_only"]), "total": int(r.sum()),
              "fatalShare": round(float(r["fatal"] / r.sum()), 6)} for y, r in counts.iterrows()]
    totals = counts.sum()
    payload = {
        "source": "Generated by analysis/code/export_site_results.py from cv_thai_all_summary.csv, "
                  "cv_thai_all_folds.csv and the harmonised accident table.",
        "nFolds": int(summary["n_folds"].iloc[0]),
        "classTotals": {"fatal": int(totals["fatal"]), "injury": int(totals["injury"]),
                        "propertyOnly": int(totals["property_only"]), "total": int(totals.sum())},
        "years": years,
        "folds": fold_rows,
        "models": models,
    }
    text = ("/* Generated file: do not edit by hand. Run analysis/code/export_site_results.py to rebuild. */\n"
            "window.RESULTS_DATA = " + json.dumps(payload, ensure_ascii=False, indent=2) + ";\n")
    (site_dir / "results-data.js").write_text(text, encoding="utf-8")
    print("wrote", site_dir / "results-data.js", "|", len(models), "model rows,", len(fold_rows), "folds,", len(years), "years")


if __name__ == "__main__":
    main(*sys.argv[1:4])
