"""Turn the recheck CSV files into the markdown tables quoted in REPORT.md (so every quoted number comes from a file).

Usage:  python -X utf8 make_report_tables.py <original_results_dir> <results_recheck_dir>
Writes <recheck>/report_tables.md.  Mean +- SD are over the four validation years (SD with ddof = 1).
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd


def pm(m, s, nd=3):
    return f"{m:.{nd}f} ± {s:.{nd}f}" if pd.notna(s) else f"{m:.{nd}f}"


def md(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def metric_table(s, keep, label_fn):
    rows = []
    for _, r in s.iterrows():
        rows.append({"model": label_fn(r), "fatal recall": pm(r.fatal_recall_mean, r.fatal_recall_sd), "fatal precision": pm(r.fatal_precision_mean, r.fatal_precision_sd),
                     "fatal F1": pm(r.fatal_f1_mean, r.fatal_f1_sd), "PR-AUC": pm(r.fatal_pr_auc_mean, r.fatal_pr_auc_sd),
                     "ROC-AUC": pm(r.fatal_auc_mean, r.fatal_auc_sd), "macro-F1": pm(r.macro_f1_mean, r.macro_f1_sd),
                     "bal. acc.": pm(r.balanced_acc_mean, r.balanced_acc_sd), "MCC": pm(r.mcc_mean, r.mcc_sd)})
    return pd.DataFrame(rows)


def main(orig_dir, out_dir):
    out = Path(out_dir)
    orig = Path(orig_dir)
    s = pd.read_csv(out / "summary_vs_original.csv")
    log_all = pd.read_csv(out / "experiment_log.csv")
    s["strategy"] = s["strategy"].replace({"default": "plain"})
    parts = ["# Report tables (generated by make_report_tables.py; mean ± SD over the 4 rolling-origin folds 2022-2025)\n"]

    # T1 baselines + original reference
    o = pd.read_csv(orig / "cv_thai_all_summary.csv")
    o["strategy"] = o["variant"].replace({"default": "plain"})
    rows = []
    for m in ("majority_class", "logistic_regression"):
        for v in (["plain"] if m == "majority_class" else ["plain", "class_weight"]):
            r = o[(o.model == m) & (o.strategy == v)].iloc[0]
            rows.append({"model": f"{m} / {v} (original file)", "fatal recall": pm(r.fatal_recall_mean, r.fatal_recall_std), "fatal precision": pm(r.fatal_precision_mean, r.fatal_precision_std),
                         "fatal F1": pm(r.fatal_f1_mean, r.fatal_f1_std), "PR-AUC": pm(r.fatal_pr_auc_mean, r.fatal_pr_auc_std), "ROC-AUC": pm(r.fatal_auc_mean, r.fatal_auc_std),
                         "macro-F1": pm(r.macro_f1_mean, r.macro_f1_std), "bal. acc.": pm(r.balanced_acc_mean, r.balanced_acc_std), "MCC": pm(r.mcc_mean, r.mcc_std)})
    parts.append("## T1. Baselines (original files, unchanged)\n" + md(pd.DataFrame(rows)) + "\n")

    # T2 exp1 + original
    e1 = s[(s.stage == "exp1_native_vs_ordinal")].copy()
    e1["order"] = e1["strategy"].map({"plain": 0, "class_weight": 1, "prior_adjusted": 2})
    e1 = e1.sort_values(["family", "encoding", "order"])
    parts.append("## T2. Native vs ordinal categoricals, original fixed settings (re-run; the ordinal rows reproduce the original CSV exactly)\n" +
                 md(metric_table(e1, None, lambda r: f"{r.family} / {r.encoding} / {r.strategy}")) + "\n")

    # T3 thresholds
    e4 = s[s.stage == "exp4_threshold"].copy().sort_values(["family", "encoding", "strategy"])
    parts.append("## T3. Decision threshold on P(fatal) chosen on the inner year (plain model; thr_f1_oracle is a diagnostic that peeks at the outer year)\n" +
                 md(metric_table(e4, None, lambda r: f"{r.family} / {r.encoding} / {r.strategy}")) + "\n")

    # T4 SMOTE
    e2 = s[s.stage == "exp2_smote"].copy().sort_values(["family", "encoding"])
    rows = metric_table(e2, None, lambda r: f"{r.family} / {r.encoding}")
    ref = []
    for fam in ("lightgbm", "xgboost"):
        r = o[(o.model == fam) & (o.variant == "smote")].iloc[0]
        ref.append({"model": f"{fam} / smote_unscaled_ordinal (ORIGINAL file)", "fatal recall": pm(r.fatal_recall_mean, r.fatal_recall_std), "fatal precision": pm(r.fatal_precision_mean, r.fatal_precision_std),
                    "fatal F1": pm(r.fatal_f1_mean, r.fatal_f1_std), "PR-AUC": pm(r.fatal_pr_auc_mean, r.fatal_pr_auc_std), "ROC-AUC": pm(r.fatal_auc_mean, r.fatal_auc_std),
                    "macro-F1": pm(r.macro_f1_mean, r.macro_f1_std), "bal. acc.": pm(r.balanced_acc_mean, r.balanced_acc_std), "MCC": pm(r.mcc_mean, r.mcc_std)})
    c = pd.read_csv(orig / "cv_thai_smote_control_folds.csv")
    for mname, g in c.groupby("model"):
        ref.append({"model": f"{mname.replace('_imputed_control', '')} / control_ordinal (ORIGINAL file)", "fatal recall": pm(g.fatal_recall.mean(), g.fatal_recall.std()),
                    "fatal precision": pm(g.fatal_precision.mean(), g.fatal_precision.std()), "fatal F1": pm(g.fatal_f1.mean(), g.fatal_f1.std()),
                    "PR-AUC": pm(g.fatal_pr_auc.mean(), g.fatal_pr_auc.std()), "ROC-AUC": pm(g.fatal_auc.mean(), g.fatal_auc.std()), "macro-F1": pm(g.macro_f1.mean(), g.macro_f1.std()),
                    "bal. acc.": pm(g.balanced_acc.mean(), g.balanced_acc.std()), "MCC": pm(g.mcc.mean(), g.mcc.std())})
    parts.append("## T4. SMOTE-NC with standardised numerics, controls, and the original SMOTE / control rows\n" + md(pd.concat([rows, pd.DataFrame(ref)], ignore_index=True)) + "\n")

    # T5 calibration
    cal = pd.read_csv(out / "calibration_summary.csv")
    rows = []
    for _, r in cal.sort_values(["family", "encoding", "strategy"]).iterrows():
        rows.append({"model": f"{r.family} / {r.encoding} / {r.strategy}", "Brier": pm(r.brier_mean, r.brier_sd, 4), "Brier skill vs constant": pm(r.brier_skill_score_mean, r.brier_skill_score_sd, 3),
                     "ECE (10 bins)": pm(r.ece_10_equal_width_mean, r.ece_10_equal_width_sd, 4), "mean pred − observed": f"{r.mean_pred_minus_observed_mean:+.4f}",
                     "calibration slope": pm(r.calibration_slope_mean, r.calibration_slope_sd, 2), "PR-AUC": pm(r.pr_auc_mean, r.pr_auc_sd, 3)})
    parts.append("## T5. Calibration of P(fatal)\n" + md(pd.DataFrame(rows)) + "\n")

    # T6 ranking equivalence
    rk = pd.read_csv(out / "ranking_equivalence_summary.csv")
    rows = []
    for _, r in rk.iterrows():
        rows.append({"model": f"{r.family} / {r.encoding}", "PR-AUC plain": pm(r.pr_auc_plain_mean, r.pr_auc_plain_sd, 4), "PR-AUC class weights": pm(r.pr_auc_class_weight_mean, r.pr_auc_class_weight_sd, 4),
                     "diff (cw − plain)": pm(r["pr_auc_diff_cw_minus_plain_mean"], r["pr_auc_diff_cw_minus_plain_sd"], 4), "Spearman rho": f"{r.spearman_plain_vs_class_weight_mean:.3f}",
                     "F1 class weights (own cut)": pm(r.class_weight_F1_own_mean, r.class_weight_F1_own_sd), "F1 plain ranking, same number of fatal calls": pm(r.class_weight_F1_plain_ranking_same_k_mean, r.class_weight_F1_plain_ranking_same_k_sd),
                     "F1 prior-adj (own cut)": pm(r.prior_adjusted_F1_own_mean, r.prior_adjusted_F1_own_sd), "F1 plain ranking, same k as prior-adj": pm(r.prior_adjusted_F1_plain_ranking_same_k_mean, r.prior_adjusted_F1_plain_ranking_same_k_sd)})
    parts.append("## T6. Do class weights / prior adjustment change the ranking? (matched number of fatal calls)\n" + md(pd.DataFrame(rows)) + "\n")

    # T7 ablation
    ab = s[(s.stage == "exp6_feature_ablation") | ((s.stage == "exp1_native_vs_ordinal") & (s.family == "lightgbm") & (s.encoding == "native") & (s.strategy.isin(["plain", "prior_adjusted"])))].copy()
    ab["set"] = ab["encoding"].str.replace("native__", "", regex=False).replace({"native": "all 17 features (reference)"})
    ab = ab.sort_values(["set", "strategy"])
    parts.append("## T7. Feature ablation (native LightGBM, plain and prior-adjusted)\n" + md(metric_table(ab, None, lambda r: f"{r.set} / {r.strategy}")) + "\n")

    # T8 tuning
    tn = s[s.stage == "exp7_tuning_native"].copy()
    if len(tn):
        parts.append("## T8. Nested tuning of native LightGBM (same 10-config budget as the original study)\n" + md(metric_table(tn.sort_values("strategy"), None, lambda r: f"{r.family} / {r.encoding} tuned / {r.strategy}")) + "\n")
    xd = s[s.stage.isin(["exp8_xgb_native_diagnostic", "exp10_ordinal_unseen_nan"])].copy()
    if len(xd):
        parts.append("## T9. Diagnostics: XGBoost native variants (exp8) and ordinal integers with unseen labels as missing (exp10)\n" +
                     md(metric_table(xd.sort_values(["family", "encoding", "strategy"]), None, lambda r: f"{r.family} / {r.encoding} / {r.strategy}")) + "\n")
        pv = log_all[log_all.stage.isin(["exp8_xgb_native_diagnostic", "exp10_ordinal_unseen_nan", "exp1_native_vs_ordinal"]) & (log_all.strategy == "plain")]
        pv = pv[pv.encoding.isin(["ordinal", "native", "native_pooled100", "native_province_ordinal", "ordinal_unseen_nan"])]
        t = pv.pivot_table(index=["family", "encoding"], columns="val_year", values="fatal_pr_auc").round(4).reset_index()
        t.columns = [str(c) for c in t.columns]
        parts.append("### T9b. Fatal PR-AUC by validation year (plain models)\n" + md(t) + "\n")

    # T10 selection
    sel = pd.read_csv(out / "selection_recheck.csv").head(14)
    rows = [{"rank": i + 1, "source": r.source, "model": f"{r.family} / {r.encoding if isinstance(r.encoding, str) else ''} / {r.strategy}" + (" [nested-tuned, exp7]" if r.stage == "exp7_tuning_native" else ""), "fatal F1": pm(r.fatal_f1_mean, r.fatal_f1_sd, 4),
             "macro-F1": f"{r.macro_f1_mean:.4f}", "fatal recall": f"{r.fatal_recall_mean:.3f}", "fatal precision": f"{r.fatal_precision_mean:.3f}", "PR-AUC": f"{r.fatal_pr_auc_mean:.4f}"} for i, r in sel.iterrows()]
    parts.append("## T10. Candidates ranked by the pre-set rule (mean fatal F1, then macro-F1) - recheck and original candidates together\n" + md(pd.DataFrame(rows)) + "\n")

    bs = out / "paired_bootstrap.csv"
    if bs.exists():
        b = pd.read_csv(bs)
        b["95% CI"] = b.apply(lambda r: f"[{r.ci95_low:+.4f}, {r.ci95_high:+.4f}]", axis=1)
        b["mean diff"] = b["mean_diff_over_folds"].map(lambda v: f"{v:+.4f}")
        parts.append("## T11. Paired bootstrap of differences (incidents resampled within each year; optimistic: ignores clustering)\n" +
                     md(b[["comparison", "mean diff", "95% CI", "per_fold_diffs_2022_2025", "interval_excludes_zero"]]) + "\n")
    (out / "report_tables.md").write_text("\n".join(parts), encoding="utf-8")
    print("\n".join(parts))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
